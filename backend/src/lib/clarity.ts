// Microsoft Clarity readout for the admin Overview (LOOM-286).
//
// Clarity's Data Export API allows 10 requests per project per day, covers only
// the last 24, 48 or 72 hours before the call (UTC), returns at most 1,000 rows
// and cannot page. So the admin page never calls Clarity: a daily cron
// (CLARITY_CRON) makes 4 requests with numOfDays=1, which gives back-to-back
// 24-hour windows and leaves 6 requests spare, and stores every answer in D1
// (migrations/0028_clarity_snapshots.sql). Nothing is retried: a retry spends
// the same daily quota. Only aggregate dimensions are requested, never a user
// or session id, and every URL is stored without query string or fragment.
//
// The docs (learn.microsoft.com/clarity/setup-and-installation/
// clarity-data-export-api) name the metrics but not the fields inside each
// metric's `information` items, and their sample mixes numeric strings with
// numbers. Parsing is therefore defensive: metric names are matched with case,
// spaces and punctuation ignored, unknown fields are kept as returned, other
// shapes are dropped, and nothing here throws when the shape drifts.
//
// Secret (wrangler secret put): CLARITY_API_TOKEN, generated by a Clarity
// project admin under Settings > Data Export.

import { sendTelegramMessage } from './telegram'
import type { Bindings } from '../types'

export const CLARITY_CRON = '0 2 * * *'
export const CLARITY_PROJECT = 'z3lrdtn5pv'
const ENDPOINT = 'https://www.clarity.ms/export-data/api/v1/project-live-insights'
const NUM_DAYS = 1

// Run order. `key` names the dimension set in the readout; the stored
// `dimensions` column is the comma-joined list ('' for none).
export const CLARITY_REQUESTS: readonly { key: string; dimensions: readonly string[] }[] = [
  { key: 'totals', dimensions: [] },
  { key: 'url', dimensions: ['URL'] },
  { key: 'device', dimensions: ['Device'] },
  { key: 'source', dimensions: ['Source', 'Medium', 'Campaign'] },
]

const LINKS = {
  dashboard: `https://clarity.microsoft.com/projects/view/${CLARITY_PROJECT}/dashboard`,
  heatmaps: `https://clarity.microsoft.com/projects/view/${CLARITY_PROJECT}/heatmaps`,
}

// Token rejected or daily quota spent: stop the run, keep earlier snapshots.
const STOP = new Set([401, 403, 429])
// D1 caps a row at 2 MB. Above this, the stored body keeps 100 items per metric.
const MAX_BODY = 1_500_000

export function clarityRequestUrl(dimensions: readonly string[]): string {
  const params = new URLSearchParams({ numOfDays: String(NUM_DAYS) })
  dimensions.forEach((name, i) => params.set(`dimension${i + 1}`, name))
  return `${ENDPOINT}?${params}`
}

const ABSOLUTE_URL = /^[a-z][a-z\d+.-]*:\/\//i
const URL_KEY = /url|referr?er|href|link/i

// A URL reduced to its path: no origin, query string or fragment.
export function toPath(value: string): string {
  if (ABSOLUTE_URL.test(value)) {
    try { return new URL(value).pathname } catch { /* not a URL after all */ }
  }
  return value.split(/[?#]/, 1)[0]
}

type Value = string | number | boolean | null
type Item = Record<string, Value>
type Metric = { metricName: string; information: Item[] }

const isObject = (value: unknown): value is Record<string, unknown> =>
  typeof value === 'object' && value !== null && !Array.isArray(value)

// Keeps the documented shape, [{ metricName, information: [{ ... }] }], and
// drops anything else (nested values included). Primitive fields stay as
// returned, except that a URL (an absolute URL, a path, or any string under a
// URL-like key) loses its query string and fragment.
export function sanitize(body: unknown): Metric[] {
  if (!Array.isArray(body)) return []
  return body.flatMap((metric) => {
    if (!isObject(metric) || typeof metric.metricName !== 'string') return []
    const items = Array.isArray(metric.information) ? metric.information.filter(isObject) : []
    const information = items.map((item) => {
      const out: Item = {}
      for (const [key, value] of Object.entries(item)) {
        if (typeof value === 'string') out[key] = ABSOLUTE_URL.test(value) || value.startsWith('/') || URL_KEY.test(key) ? toPath(value) : value
        else if (value === null || typeof value === 'number' || typeof value === 'boolean') out[key] = value
      }
      return out
    })
    return [{ metricName: metric.metricName, information }]
  })
}

function serialize(metrics: Metric[]): string {
  const text = JSON.stringify(metrics)
  if (text.length <= MAX_BODY) return text
  // ponytail: crude cap for an answer near D1's row limit; Clarity's row order is kept.
  return JSON.stringify(metrics.map((m) => ({ ...m, information: m.information.slice(0, 100) })))
}

type Deps = { fetch: typeof fetch; now: () => number; notify: (html: string) => Promise<void> }
type RunEnv = Pick<Bindings, 'DB' | 'CLARITY_API_TOKEN' | 'TELEGRAM_BOT_TOKEN' | 'TELEGRAM_CHAT_ID'>

// The daily cron. One row per request, failures included; a failed run sends
// one Telegram message. Without CLARITY_API_TOKEN it does nothing.
export async function pullClarity(env: RunEnv, overrides: Partial<Deps> = {}): Promise<void> {
  const deps: Deps = {
    fetch: ((input, init) => fetch(input, init)) as typeof fetch,
    now: Date.now,
    notify: async (html) => {
      if (env.TELEGRAM_BOT_TOKEN && env.TELEGRAM_CHAT_ID) await sendTelegramMessage(env.TELEGRAM_BOT_TOKEN, env.TELEGRAM_CHAT_ID, html)
    },
    ...overrides,
  }
  const token = env.CLARITY_API_TOKEN?.trim()
  if (!token) return
  const fetchedAt = new Date(deps.now()).toISOString()
  const failed: { name: string; status: number }[] = []
  for (const { key, dimensions } of CLARITY_REQUESTS) {
    let status = 0
    let body: string | null = null
    try {
      const res = await deps.fetch(clarityRequestUrl(dimensions), {
        headers: { Authorization: `Bearer ${token}`, 'Content-Type': 'application/json' },
      })
      status = res.status
      if (res.ok) body = serialize(sanitize(await res.json()))
    } catch (error) {
      // No answer, or a 200 that is not JSON: recorded below, never retried.
      console.error(`[clarity] ${key}: ${error instanceof Error ? error.message : 'error'}`)
    }
    await env.DB.prepare('INSERT INTO clarity_snapshots (fetched_at, dimensions, num_days, status, body) VALUES (?, ?, ?, ?, ?)')
      .bind(fetchedAt, dimensions.join(','), NUM_DAYS, status, body).run()
    if (body === null) failed.push({ name: key, status })
    if (STOP.has(status)) break
  }
  if (!failed.length) {
    console.log(`[clarity] ${CLARITY_REQUESTS.length} snapshots stored`)
    return
  }
  const statuses = failed.map((f) => f.status)
  const hint = statuses.includes(429)
    ? 'Дневной лимит Clarity (10 запросов) исчерпан. Не вызывайте API вручную.'
    : statuses.some((s) => s === 401 || s === 403)
      ? 'Clarity отклонил токен. Создайте новый (Settings → Data Export) и обновите CLARITY_API_TOKEN.'
      : 'Следующая попытка — завтра в 02:00 UTC.'
  await deps.notify(`⛔ Clarity: ежедневная выгрузка не удалась (${failed.map((f) => `${f.name}: HTTP ${f.status}`).join(', ')}). Прошлые данные сохранены.\n${hint}`)
}

const norm = (name: unknown) => String(name).toLowerCase().replace(/[^a-z\d]/g, '')
const num = (value: unknown): number | null => {
  const n = typeof value === 'number' ? value : typeof value === 'string' && value.trim() ? Number(value) : NaN
  return Number.isFinite(n) ? n : null
}

// Metrics keyed by normalized name ('Rage Click Count' and 'RageClickCount'
// are both 'rageclickcount'), numeric strings as numbers.
function readMetrics(text: string): Record<string, Item[]> {
  let parsed: unknown = null
  try { parsed = JSON.parse(text) } catch { /* stored by us, but never trust a shape */ }
  const out: Record<string, Item[]> = {}
  for (const metric of sanitize(parsed)) {
    const items = metric.information.map((item) => Object.fromEntries(Object.entries(item).map(([k, v]) => [k, num(v) ?? v])))
    out[norm(metric.metricName)] = [...(out[norm(metric.metricName)] ?? []), ...items]
  }
  return out
}

// The trend's count field is not documented either. Samples seen in the wild
// carry sessionsCount, sessionsWithMetricPercentage, pagesViews and subTotal
// (the click count). No count field means null, a gap in the trend, never 0.
const COUNT_FIELDS = ['subtotal', 'count', 'total']
export function pickCount(item: unknown): number | null {
  if (!isObject(item)) return null
  const fields = new Map(Object.entries(item).map(([k, v]) => [norm(k), num(v)]))
  for (const name of COUNT_FIELDS) {
    const value = fields.get(name)
    if (value != null) return value
  }
  return null
}

const OK = 'status = 200 AND body IS NOT NULL'
// Bodies are parsed in SQLite, not the Worker: only each metric's first item
// comes back for the 30 newest totals snapshots.
const TREND_SQL = `SELECT s.fetched_at AS fetchedAt, m.value ->> '$.metricName' AS metric, m.value -> '$.information[0]' AS first
  FROM (SELECT fetched_at, body FROM clarity_snapshots WHERE dimensions = '' AND ${OK} AND json_valid(body) ORDER BY fetched_at DESC LIMIT 30) AS s,
    json_each(s.body) AS m
  WHERE m.type = 'object'`
const TREND_FIELDS = new Map<string, 'rageClicks' | 'deadClicks'>([['rageclickcount', 'rageClicks'], ['deadclickcount', 'deadClicks']])

type Snapshot = { fetchedAt: string; numDays: number; metrics: Record<string, Item[]> }
type TrendPoint = { fetchedAt: string; rageClicks: number | null; deadClicks: number | null }

// GET /api/admin/analytics/clarity. Reads D1 only; call after requireAdmin + requireCap.
export async function clarityReadout(env: Pick<Bindings, 'DB' | 'CLARITY_API_TOKEN'>): Promise<Record<string, unknown>> {
  if (!env.CLARITY_API_TOKEN?.trim()) return { configured: false, missing: ['CLARITY_API_TOKEN'] }
  const latestSql = env.DB.prepare(`SELECT fetched_at, num_days, body FROM clarity_snapshots WHERE dimensions = ? AND ${OK} ORDER BY fetched_at DESC, id DESC LIMIT 1`)
  const results = await env.DB.batch([
    ...CLARITY_REQUESTS.map((r) => latestSql.bind(r.dimensions.join(','))),
    env.DB.prepare(TREND_SQL),
    env.DB.prepare(`SELECT fetched_at, dimensions, status FROM clarity_snapshots WHERE NOT (${OK}) ORDER BY fetched_at DESC, id DESC LIMIT 1`),
  ])

  const latest: Record<string, Snapshot | null> = {}
  CLARITY_REQUESTS.forEach(({ key }, i) => {
    const row = results[i].results[0] as { fetched_at: string; num_days: number; body: string } | undefined
    latest[key] = row ? { fetchedAt: row.fetched_at, numDays: row.num_days, metrics: readMetrics(row.body) } : null
  })

  const points = new Map<string, TrendPoint>()
  for (const row of results[CLARITY_REQUESTS.length].results as { fetchedAt: string; metric: unknown; first: string | null }[]) {
    const field = TREND_FIELDS.get(norm(row.metric))
    if (!field) continue
    const point = points.get(row.fetchedAt) ?? { fetchedAt: row.fetchedAt, rageClicks: null, deadClicks: null }
    let first: unknown = null
    try { first = JSON.parse(row.first ?? 'null') } catch { /* gap */ }
    point[field] = pickCount(first)
    points.set(row.fetchedAt, point)
  }
  const trend = [...points.values()].sort((a, b) => a.fetchedAt.localeCompare(b.fetchedAt))

  const error = results[CLARITY_REQUESTS.length + 1].results[0] as { fetched_at: string; dimensions: string; status: number } | undefined
  const lastError = error
    ? { fetchedAt: error.fetched_at, request: CLARITY_REQUESTS.find((r) => r.dimensions.join(',') === error.dimensions)?.key ?? error.dimensions, status: error.status }
    : null
  return { configured: true, project: CLARITY_PROJECT, links: LINKS, latest, trend, lastError }
}
